export const BRANCH_MAP: Record<string, BranchInfo> = Object.fromEntries(
  BRANCHES.map((b) => [b.id, b]),
) as Record<string, BranchInfo>;

export function branchInfo(id: string | null | undefined): BranchInfo {
  return (id && BRANCH_MAP[id]) || BRANCHES[0]!;
}

